def build(arts_meta):
    rank = []
    for i, a in enumerate(arts_meta):
        s = SCORES[i]; total = sum(s[:5])
        rank.append(dict(i=i, title=a[3], url=a[4], dt=a[2], wk=a[0], s=list(s[:5]), total=total, tier=tier(total), note=s[5]))
    rank.sort(key=lambda r: -r["total"])
    for n, r in enumerate(rank): r["pos"] = n + 1
    quizzes = []
    for k, (idx, label, qs) in enumerate(QUIZ):
        assert len(qs) == 10, label
        out = []
        for j, (q, right, wrong, par, why) in enumerate(qs):
            assert len(wrong) == 4, (label, j)
            p = POS[k][j]; opts = wrong[:p] + [right] + wrong[p:]
            out.append(dict(stem=q, opts=opts, ans=p, par=par, why=why))
        assert sorted(x["ans"] for x in out) == [0,0,1,1,2,2,3,3,4,4], label
        a = arts_meta[idx]
        quizzes.append(dict(id="p%d" % idx, idx=idx, title=a[3], url=a[4], dt=a[2], total=sum(SCORES[idx][:5]), qs=out))
    return dict(rubric=[list(r) for r in RUBRIC], rank=rank, quizzes=quizzes, scans=[[d, [list(x) for x in L]] for d, L in SCANS])
